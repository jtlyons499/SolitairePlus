def select_interview(recent_ids=(), rng=None, count=3):
    rng = rng or random
    recent = set(recent_ids)
    fresh = [q for q in PRESS_INTERVIEW_QUESTION_POOL if q['id'] not in recent]
    candidates = fresh if len(fresh) >= count else list(PRESS_INTERVIEW_QUESTION_POOL)
    picked, topics = [], set()
    while candidates and len(picked) < count:
        distinct = [q for q in candidates if q['topic'] not in topics]
        question = rng.choice(distinct or candidates)
        candidates.remove(question)
        topics.add(question['topic'])
        question = copy.deepcopy(question)
        rng.shuffle(question['answers'])
        picked.append(question)
    return picked


def answer_outcome(old_heat, answer, rating, fans):
    _, heat_delta, appeal = answer
    heat = max(-100, min(100, old_heat + int(heat_delta)))
    popularity = max(90, int(120 + float(rating)*.18 + math.sqrt(max(0, fans))*2.2))
    heat_scale = 1 + max(-.35, min(.45, old_heat/180))
    return heat, round(popularity*float(appeal)*heat_scale)
